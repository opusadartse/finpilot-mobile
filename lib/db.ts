const db = SQLite.openDatabaseSync("finpilot_mobile.db");
let initialized = false;

const USER_BASE_CREDIT_SCORE_KEY = "user_base_credit_score";

export function initDb() {
  if (initialized) return;
  db.execSync(`
    PRAGMA journal_mode = WAL;
    CREATE TABLE IF NOT EXISTS cards (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      name TEXT NOT NULL,
      credit_limit REAL NOT NULL,
      current_balance REAL NOT NULL,
      apr REAL NOT NULL,
      min_payment REAL NOT NULL,
      due_date TEXT NOT NULL,
      opening_date TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS payments (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      card_id INTEGER NOT NULL,
      amount REAL NOT NULL,
      paid_at TEXT NOT NULL,
      balance_after REAL NOT NULL,
      FOREIGN KEY(card_id) REFERENCES cards(id) ON DELETE CASCADE
    );
    CREATE TABLE IF NOT EXISTS score_history (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      estimated_score INTEGER NOT NULL,
      utilization REAL NOT NULL,
      created_at TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS loan_promotions (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      name TEXT NOT NULL,
      amount_borrowed REAL NOT NULL,
      current_balance REAL NOT NULL,
      start_date TEXT NOT NULL,
      end_date TEXT NOT NULL,
      monthly_payment_target REAL NOT NULL,
      purchases_this_month REAL NOT NULL DEFAULT 0,
      purchases_month TEXT NOT NULL DEFAULT '',
      interest_free_expiration TEXT NOT NULL,
      notes TEXT NOT NULL DEFAULT ''
    );
    CREATE TABLE IF NOT EXISTS loan_payments (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      loan_id INTEGER NOT NULL,
      amount REAL NOT NULL,
      paid_at TEXT NOT NULL,
      balance_after REAL NOT NULL,
      FOREIGN KEY(loan_id) REFERENCES loan_promotions(id) ON DELETE CASCADE
    );
    CREATE TABLE IF NOT EXISTS app_settings (
      key TEXT PRIMARY KEY NOT NULL,
      value TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS payment_reminders (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      title TEXT NOT NULL,
      amount_due REAL NOT NULL,
      due_date TEXT NOT NULL,
      notes TEXT NOT NULL DEFAULT '',
      repeat_monthly INTEGER NOT NULL DEFAULT 0,
      is_paid INTEGER NOT NULL DEFAULT 0,
      paid_at TEXT,
      payment_source TEXT NOT NULL DEFAULT '',
      source_type TEXT NOT NULL DEFAULT 'manual',
      source_id INTEGER,
      created_at TEXT NOT NULL,
      updated_at TEXT NOT NULL,
      UNIQUE(source_type, source_id)
    );
    CREATE TABLE IF NOT EXISTS reminder_payment_history (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      reminder_id INTEGER NOT NULL,
      paid_at TEXT NOT NULL,
      amount REAL NOT NULL,
      payment_source TEXT NOT NULL DEFAULT '',
      FOREIGN KEY(reminder_id) REFERENCES payment_reminders(id) ON DELETE CASCADE
    );
  `);
  ensureLoanPurchasesColumn();
  ensureLoanPurchasesMonthColumn();
  ensureReminderSchema();

  const count = db.getFirstSync<{ count: number }>("SELECT COUNT(*) as count FROM cards");
  // Keep "Sam Faz" for branding only (icon/splash), not as a seeded card record.
  db.runSync(`UPDATE cards SET name = 'Amex Platinum' WHERE name = 'Amex Sam Faz'`);
  if ((count?.count ?? 0) === 0) seedDemoData();
  syncAutoGeneratedRemindersForAll();
  initialized = true;
}

