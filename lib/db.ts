export function addLoan(
  input: Omit<LoanPromotionRow, "id" | "current_balance" | "monthly_payment_target" | "purchases_this_month" | "purchases_month"> & {
    current_balance?: number;
    monthly_payment_target?: number;
    purchases_this_month?: number;
  }
) {
  initDb();
  const balance = Number.isFinite(input.current_balance) ? Number(input.current_balance) : input.amount_borrowed;
  const months = Math.max(1, getRemainingMonths(input.interest_free_expiration));
  const monthly = Number.isFinite(input.monthly_payment_target) && (input.monthly_payment_target ?? 0) > 0
    ? Number(input.monthly_payment_target)
    : balance / months;
  const result = db.runSync(
    `INSERT INTO loan_promotions
      (name, amount_borrowed, current_balance, start_date, end_date, monthly_payment_target, purchases_this_month, purchases_month, interest_free_expiration, notes)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
    input.name,
    input.amount_borrowed,
    balance,
    input.start_date,
    input.end_date,
    monthly,
    input.purchases_this_month ?? 0,
    getCurrentMonthKey(),
    input.interest_free_expiration,
    input.notes ?? ""
  );
  const inserted = db.getFirstSync<LoanPromotionRow>("SELECT * FROM loan_promotions WHERE id = ?", result.lastInsertRowId);
  if (inserted) syncLoanReminder(inserted);
}

