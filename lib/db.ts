function ensureLoanPurchasesColumn() {
  const columns = db.getAllSync<{ name: string }>("PRAGMA table_info(loan_promotions)");
  const hasPurchasesColumn = columns.some((col) => col.name === "purchases_this_month");
  if (!hasPurchasesColumn) {
    db.runSync("ALTER TABLE loan_promotions ADD COLUMN purchases_this_month REAL NOT NULL DEFAULT 0");
  }
}

function ensureLoanPurchasesMonthColumn() {
  const columns = db.getAllSync<{ name: string }>("PRAGMA table_info(loan_promotions)");
  const hasPurchasesMonthColumn = columns.some((col) => col.name === "purchases_month");
  if (!hasPurchasesMonthColumn) {
    db.runSync("ALTER TABLE loan_promotions ADD COLUMN purchases_month TEXT NOT NULL DEFAULT ''");
  }
}

function getCurrentMonthKey() {
  const now = new Date();
  const month = String(now.getMonth() + 1).padStart(2, "0");
  return `${now.getFullYear()}-${month}`;
}

function ensureReminderSchema() {
  const reminderColumns = db.getAllSync<{ name: string }>("PRAGMA table_info(payment_reminders)");
  const neededColumns: Array<{ name: string; sql: string }> = [
    { name: "payment_source", sql: "ALTER TABLE payment_reminders ADD COLUMN payment_source TEXT NOT NULL DEFAULT ''" },
    { name: "source_type", sql: "ALTER TABLE payment_reminders ADD COLUMN source_type TEXT NOT NULL DEFAULT 'manual'" },
    { name: "source_id", sql: "ALTER TABLE payment_reminders ADD COLUMN source_id INTEGER" },
    { name: "created_at", sql: "ALTER TABLE payment_reminders ADD COLUMN created_at TEXT NOT NULL DEFAULT ''" },
    { name: "updated_at", sql: "ALTER TABLE payment_reminders ADD COLUMN updated_at TEXT NOT NULL DEFAULT ''" },
  ];
  neededColumns.forEach((column) => {
    if (!reminderColumns.some((c) => c.name === column.name)) {
      db.runSync(column.sql);
    }
  });
  const nowIso = new Date().toISOString();
  db.runSync("UPDATE payment_reminders SET created_at = COALESCE(NULLIF(created_at, ''), ?) WHERE created_at IS NULL OR created_at = ''", nowIso);
  db.runSync("UPDATE payment_reminders SET updated_at = COALESCE(NULLIF(updated_at, ''), ?) WHERE updated_at IS NULL OR updated_at = ''", nowIso);
}

function getNextMonthlyDueDate(baseIsoDate: string) {
  const now = new Date();
  const base = new Date(baseIsoDate);
  const day = Number.isFinite(base.getDate()) ? base.getDate() : now.getDate();
  let year = now.getFullYear();
  let month = now.getMonth();
  let candidate = new Date(year, month, day, 9, 0, 0, 0);
  if (candidate.getTime() < now.getTime()) {
    month += 1;
    if (month > 11) {
      month = 0;
      year += 1;
    }
    candidate = new Date(year, month, day, 9, 0, 0, 0);
  }
  return candidate.toISOString();
}

function upsertAutoReminder(input: {
  sourceType: ReminderSourceType;
  sourceId: number;
  title: string;
  amountDue: number;
  dueDate: string;
  notes: string;
  repeatMonthly: number;
}) {
  const nowIso = new Date().toISOString();
  const existing = db.getFirstSync<ReminderRow>(
    "SELECT * FROM payment_reminders WHERE source_type = ? AND source_id = ?",
    input.sourceType,
    input.sourceId
  );
  if (existing) {
    const shouldKeepPaid = existing.is_paid === 1 && new Date(existing.due_date).getTime() >= new Date(input.dueDate).getTime();
    db.runSync(
      `UPDATE payment_reminders
       SET title = ?, amount_due = ?, due_date = ?, notes = ?, repeat_monthly = ?, is_paid = ?, paid_at = ?, updated_at = ?
       WHERE id = ?`,
      input.title,
      input.amountDue,
      input.dueDate,
      input.notes,
      input.repeatMonthly,
      shouldKeepPaid ? existing.is_paid : 0,
      shouldKeepPaid ? existing.paid_at : null,
      nowIso,
      existing.id
    );
    return;
  }
  db.runSync(
    `INSERT INTO payment_reminders
      (title, amount_due, due_date, notes, repeat_monthly, is_paid, paid_at, payment_source, source_type, source_id, created_at, updated_at)
     VALUES (?, ?, ?, ?, ?, 0, NULL, '', ?, ?, ?, ?)`,
    input.title,
    input.amountDue,
    input.dueDate,
    input.notes,
    input.repeatMonthly,
    input.sourceType,
    input.sourceId,
    nowIso,
    nowIso
  );
}

function syncCardReminder(card: CardRow) {
  const amountDue = Math.max(0, Number(card.min_payment) || 0);
  upsertAutoReminder({
    sourceType: "card",
    sourceId: card.id,
    title: `${card.name} Payment`,
    amountDue,
    dueDate: card.due_date,
    notes: "Auto reminder from credit card",
    repeatMonthly: 1,
  });
}

function syncLoanReminder(loan: LoanPromotionRow) {
  const amountDue = Math.max(0, Number(loan.monthly_payment_target) || 0);
  upsertAutoReminder({
    sourceType: "loan",
    sourceId: loan.id,
    title: `${loan.name} Promotion Payment`,
    amountDue,
    dueDate: getNextMonthlyDueDate(loan.end_date || loan.interest_free_expiration),
    notes: "Auto reminder from loan or promotion",
    repeatMonthly: 1,
  });
}

function syncAutoGeneratedRemindersForAll() {
  const cards = db.getAllSync<CardRow>("SELECT * FROM cards");
  cards.forEach(syncCardReminder);
  const loans = db.getAllSync<LoanPromotionRow>("SELECT * FROM loan_promotions");
  loans.forEach(syncLoanReminder);
}

