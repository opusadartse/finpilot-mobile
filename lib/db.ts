export function getRemainingMonths(isoDate: string) {
  const now = new Date();
  const end = new Date(isoDate);
  const diffMs = end.getTime() - now.getTime();
  if (!Number.isFinite(diffMs)) return 0;
  return Math.max(0, Math.ceil(diffMs / (1000 * 60 * 60 * 24 * 30)));
}

/** User-entered real credit score (300–850), persisted locally. */
export function getUserBaseScore(): number | null {
  initDb();
  const row = db.getFirstSync<{ value: string }>(
    "SELECT value FROM app_settings WHERE key = ?",
    USER_BASE_CREDIT_SCORE_KEY
  );
  if (!row?.value) return null;
  const n = Number.parseInt(row.value, 10);
  if (!Number.isFinite(n) || n < 300 || n > 850) return null;
  return n;
}

export function setUserBaseScore(score: number) {
  initDb();
  const clamped = Math.max(300, Math.min(850, Math.round(score)));
  db.runSync(
    `INSERT INTO app_settings (key, value) VALUES (?, ?)
     ON CONFLICT(key) DO UPDATE SET value = excluded.value`,
    USER_BASE_CREDIT_SCORE_KEY,
    String(clamped)
  );
}

