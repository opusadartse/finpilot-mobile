export function addLoanPayment(loanId: number, amount: number, paidAt: string) {
  initDb();
  const loan = db.getFirstSync<LoanPromotionRow>("SELECT * FROM loan_promotions WHERE id = ?", loanId);
  if (!loan) return;
  const balanceAfter = Math.max(0, loan.current_balance - amount);
  const months = Math.max(1, getRemainingMonths(loan.interest_free_expiration));
  const monthly = balanceAfter > 0 ? balanceAfter / months : 0;
  db.runSync(
    "UPDATE loan_promotions SET current_balance = ?, monthly_payment_target = ? WHERE id = ?",
    balanceAfter,
    monthly,
    loanId
  );
  db.runSync(
    `INSERT INTO loan_payments (loan_id, amount, paid_at, balance_after) VALUES (?, ?, ?, ?)`,
    loanId,
    amount,
    paidAt,
    balanceAfter
  );
}

